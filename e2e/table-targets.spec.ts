test('targets public cards and life without moving cards or changing life', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await page.evaluate(async () => {
    const vueUrl = performance.getEntriesByType('resource').map(entry => entry.name).find(url => url.includes('/node_modules/.vite/deps/vue.js')) ?? '/node_modules/.vite/deps/vue.js';
    const { createApp, h, ref } = await import(vueUrl);
    const { default: GameTable } = await import('/src/components/GameTable.vue');
    await (await import('/src/services/storage.ts')).localRepository.setPreference('hide-table-tutorial', true);
    const host = document.createElement('div'); host.style.cssText = 'position:fixed;inset:0;z-index:1'; document.body.append(host);
    const seats = ['northWest', 'southWest'].map(id => ({ id, name: id === 'northWest' ? 'Ana' : 'Lia', status: 'playing', commanderIds: [], library: [], hand: [], mulligans: 0, keptHand: true, life: 40, poison: 0, commanderCasts: {}, commanderDamage: {}, landPlays: 0 }));
    const makeCard = (id: string, ownerId: string, x: number) => ({ id, ownerId, controllerId: ownerId, cardId: id, zone: 'battlefield', tapped: false, faceDown: false, x, y: 38, counters: {}, card: { id, oracle_id: id, name: id, layout: 'normal', color_identity: [], keywords: [], mana_cost: '', type_line: 'Creature', oracle_text: '', legalities: {} } });
    const state = { id: 'targets-e2e', revision: 0, phase: 'playing', paused: false, activeSeatId: 'southWest', turn: 1, step: 'Principal', seats, cards: { cardA: makeCard('cardA', 'southWest', 42), cardB: makeCard('cardB', 'northWest', 45) }, stack: [], passes: [], log: [], updatedAt: Date.now() };
    const marks = ref<any[]>([]); (window as any).targetEvents = []; (window as any).targetActions = [];
    createApp({ render: () => h(GameTable, { state, seatId: 'southWest', playmatIds: {}, online: false, targetMarks: marks.value, onActions: (actions: unknown[]) => (window as any).targetActions.push(...actions), onTarget: (intent: any) => { (window as any).targetEvents.push(intent); marks.value = [...marks.value, { ...intent, uid: 'local', seatId: 'southWest', at: Date.now() }]; } }) }).mount(host);
  });
  await page.locator('.topbar-actions .icon-button[title="Visão geral"]').click();
  const cardA = page.locator('[data-card-id="cardA"]');
  const cardB = page.locator('[data-card-id="cardB"]');
  const life = page.locator('.seat-place[data-seat="northWest"] .seat-life-reading');
  await page.keyboard.down('Alt');
  await expect(page.locator('body')).toHaveClass(/has-target-mode/);
  await cardB.click();
  await expect.poll(() => page.evaluate(() => (window as any).targetEvents.length)).toBe(1);
  await expect(page.locator('.target-outline')).toHaveCount(1);
  const from = (await cardA.boundingBox())!, to = (await life.boundingBox())!;
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 8 });
  await page.mouse.up();
  await page.keyboard.up('Alt');
  await expect.poll(() => page.evaluate(() => (window as any).targetEvents.length)).toBe(2);
  const events = await page.evaluate(() => (window as any).targetEvents);
  expect(events[0]).toMatchObject({ kind: 'highlight', target: { kind: 'card', cardId: 'cardB' } });
  expect(events[1]).toMatchObject({ kind: 'arrow', origin: { kind: 'card', cardId: 'cardA' }, target: { kind: 'player', seatId: 'northWest' } });
  expect(await page.evaluate(() => (window as any).targetActions)).toEqual([]);
  await cardA.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Dar alvo com esta carta' }).click();
  await expect(page.getByText('Selecione o destino')).toBeVisible();
  await cardB.click();
  await expect.poll(() => page.evaluate(() => (window as any).targetEvents.length)).toBe(3);
  expect((await page.evaluate(() => (window as any).targetEvents))[2]).toMatchObject({ kind: 'arrow', origin: { cardId: 'cardA' }, target: { cardId: 'cardB' } });
  expect(await page.evaluate(() => (window as any).targetActions)).toEqual([]);
  await cardA.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Dar alvo com esta carta' }).click();
  await page.keyboard.press('Escape');
  await expect(page.getByText('Selecione o destino')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => (window as any).targetEvents.length)).toBe(3);
  const bounds = (await life.boundingBox())!;
  const touch = { bubbles: true, pointerType: 'touch', pointerId: 23, isPrimary: true, button: 0, clientX: bounds.x + bounds.width / 2, clientY: bounds.y + bounds.height / 2 };
  await life.dispatchEvent('pointerdown', touch);
  await page.waitForTimeout(550);
  await life.dispatchEvent('pointerup', touch);
  await page.getByRole('menuitem', { name: 'Selecionar este alvo' }).click();
  await expect.poll(() => page.evaluate(() => (window as any).targetEvents.length)).toBe(4);
  expect((await page.evaluate(() => (window as any).targetEvents))[3]).toMatchObject({ kind: 'highlight', target: { kind: 'player', seatId: 'northWest' } });
  await cardA.focus();
  await page.keyboard.press('Shift+F10');
  await page.getByRole('menuitem', { name: 'Dar alvo com esta carta' }).click();
  await life.focus();
  await page.keyboard.press('Enter');
  await expect.poll(() => page.evaluate(() => (window as any).targetEvents.length)).toBe(5);
  expect((await page.evaluate(() => (window as any).targetEvents))[4]).toMatchObject({ kind: 'arrow', origin: { cardId: 'cardA' }, target: { kind: 'player', seatId: 'northWest' } });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => page.evaluate(() => {
    const stage = document.querySelector('.table-stage')!.getBoundingClientRect();
    const life = document.querySelector('.seat-place[data-seat="northWest"] .seat-life-reading')!.getBoundingClientRect();
    const line = document.querySelector('.target-line:not(.target-line-preview)')!;
    const x = Number(line.getAttribute('x2')), y = Number(line.getAttribute('y2'));
    const left = life.left - stage.left, top = life.top - stage.top;
    return Math.round(Math.max(left - x, x - (left + life.width), top - y, y - (top + life.height), 0));
  })).toBeLessThan(3);
});

test('expires successive local marks independently after ten seconds', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await page.evaluate(async decks => {
    const { localRepository } = await import('/src/services/storage.ts');
    for (const deck of decks) await localRepository.saveDeck(deck);
  }, preconFixtureDecks());
  await startLocalDemo(page);
  await page.locator('.topbar-actions .icon-button[title="Visão geral"]').click();
  const lifeA = page.locator('.seat-place[data-seat="northWest"] .seat-life-reading');
  const lifeB = page.locator('.seat-place[data-seat="northEast"] .seat-life-reading');
  await page.keyboard.down('Alt');
  await lifeA.click();
  await expect(page.locator('.target-layer .target-outline')).toHaveCount(1);
  await page.waitForTimeout(2000);
  await lifeB.click();
  await page.keyboard.up('Alt');
  await expect(page.locator('.target-layer .target-outline')).toHaveCount(2);
  await expect(page.locator('.target-layer .target-outline')).toHaveCount(1, { timeout: 9000 });
  await expect(page.locator('.target-layer .target-outline')).toHaveCount(0, { timeout: 4000 });
});

test('target preview leaves 200 card fields unchanged during pointer movement', async ({ page }) => {
  await page.goto('/');
  await page.evaluate(async () => {
    const vueUrl = performance.getEntriesByType('resource').map(entry => entry.name).find(url => url.includes('/node_modules/.vite/deps/vue.js')) ?? '/node_modules/.vite/deps/vue.js';
    const { createApp, h } = await import(vueUrl);
    const { default: GameTable } = await import('/src/components/GameTable.vue');
    await (await import('/src/services/storage.ts')).localRepository.setPreference('hide-table-tutorial', true);
    const { startDemoMatch, addStressObjects } = await import('/src/services/demo.ts');
    const { fixtureDecks } = await import('/tests/fixtures/scryfall.ts');
    const state = addStressObjects(startDemoMatch('Lia', fixtureDecks()), 200);
    const host = document.createElement('div'); host.style.cssText = 'position:fixed;inset:0;z-index:1'; document.body.append(host);
    (window as any).targetFieldUpdates = 0;
    const app = createApp({ render: () => h(GameTable, { state, seatId: 'southWest', playmatIds: {}, online: false }) });
    app.mixin({ updated() { if ((this as any).$options.__name === 'TableField') (window as any).targetFieldUpdates++; } });
    app.mount(host);
  });
  await expect(page.locator('.board-card-wrap[data-card-id*="-stress-"]')).toHaveCount(200);
  await page.locator('.topbar-actions .icon-button[title="Visão geral"]').click();
  const card = page.locator('.mat-southWest .board-card-wrap').first();
  const box = (await card.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.keyboard.down('Alt');
  await page.mouse.down();
  await page.evaluate(() => { (window as any).targetFieldUpdates = 0; });
  for (let i = 0; i < 20; i++) await page.mouse.move(box.x + box.width / 2 + i * 5, box.y + box.height / 2 - i * 3);
  await expect(page.locator('.target-line-preview')).toHaveCount(1);
  expect(await page.evaluate(() => (window as any).targetFieldUpdates)).toBe(0);
  await page.mouse.up(); await page.keyboard.up('Alt');
});
